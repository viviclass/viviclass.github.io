// 繁體化：字元級簡轉繁 + 詞組修正
// 字元表是用 Windows 的 LCMapStringEx(zh-TW, LCMAP_TRADITIONAL_CHINESE)
// 掃 U+4E00..U+9FFF 產生的，共 2191 組。
import { S2T_PAIRS } from './s2t-pairs.js';

const CHAR_MAP = new Map();
for (let i = 0; i < S2T_PAIRS.length; i += 2) CHAR_MAP.set(S2T_PAIRS[i], S2T_PAIRS[i + 1]);

// Windows 會把「台」轉成「臺」，但台灣日常寫法是「台」。拿掉這條。
CHAR_MAP.delete('台');

// 詞組修正。字元級轉換處理不了的三種情況：
//   1.「后、里、复、干、面」這些字繁體本來就有，字元轉換不會動它們 → 要看詞組
//   2. 大陸用語（視頻、軟件）字形已經是繁體，但用字不同
//   3. 語音辨識常見的同音錯誤
// 來源：ViVi 剪麵包老師課程時累積校對出來的表，這裡只收通用的，
//       課程專有名詞（人名、商品名、第幾計）沒有收進來。
const PHRASES = [
  // ── 「后」不是「後」 ──
  ['之后','之後'],['最后','最後'],['以后','以後'],['然后','然後'],['后面','後面'],
  ['后來','後來'],['背后','背後'],['落后','落後'],['過后','過後'],['完后','完後'],
  ['后台','後台'],['后臺','後台'],['后續','後續'],['后期','後期'],['稍后','稍後'],
  // ── 「于」不是「於」 ──
  ['屬于','屬於'],['對于','對於'],['由于','由於'],['關于','關於'],['于是','於是'],
  ['在于','在於'],['等于','等於'],['基于','基於'],['終于','終於'],['至于','至於'],
  // ── 「么」不是「麼」 ──
  ['什么','什麼'],['這么','這麼'],['那么','那麼'],['怎么','怎麼'],['多么','多麼'],
  // ── 「里」不是「裡」 ──
  ['里面','裡面'],['家里','家裡'],['這里','這裡'],['那里','那裡'],['哪里','哪裡'],
  ['心里','心裡'],['手里','手裡'],['房間里','房間裡'],['店里','店裡'],['城里','城裡'],
  // ── 「余」不是「餘」 ──
  ['之余','之餘'],['業余','業餘'],['其余','其餘'],['剩余','剩餘'],
  // ── 「复」「制」「范」 ──
  ['復制','複製'],['復雜','複雜'],['制作','製作'],['制造','製造'],['制品','製品'],
  ['規范','規範'],['范圍','範圍'],['示范','示範'],['模范','模範'],
  // ── 大陸用語 → 台灣用語 ──
  ['注冊','註冊'],['視頻','影片'],['音頻','音訊'],['軟件','軟體'],['硬件','硬體'],
  ['網絡','網路'],['鏈接','連結'],['賬號','帳號'],['賬戶','帳戶'],['默認','預設'],
  ['屏幕','螢幕'],['菜單','選單'],['點贊','按讚'],['按贊','按讚'],['博主','版主'],
  ['運營','營運'],['信息','訊息'],['計劃','計畫'],['社羣','社群'],['質量','品質'],
  ['人工智能','人工智慧'],['智能手機','智慧手機'],['智能音箱','智慧音箱'],['智能家電','智慧家電'],
  ['數據','數據'],['視頻號','影片'],['公眾號','粉專'],['小視頻','短影片'],
  // ── 台灣用字：一律用「台」 ──
  ['平臺','平台'],['全臺','全台'],['臺灣','台灣'],['電視臺','電視台'],['後臺','後台'],
  ['臺北','台北'],['臺中','台中'],['臺南','台南'],['臺東','台東'],
  // ── 語音辨識常見同音錯誤（通用的）──
  ['回復給','回覆給'],['回復你','回覆你'],['等老師回復','等老師回覆'],
  ['身份證','身分證'],['身份','身分'],['傭金','佣金'],
  ['D 卡','Dcard'],['D卡','Dcard'],
  ['GDP','GPT'],['GPP','GPT'],['GTP','GPT'],
  ['Seedance2.0','Seedance 2.0'],['C-Dance','Seedance'],['Cdance','Seedance'],
  ['吉夢','即夢'],
];
// 長的先換，避免短規則先吃掉長規則該管的範圍
PHRASES.sort((a, b) => b[0].length - a[0].length);

/** 字元級簡轉繁 */
export function toTraditional(s) {
  let out = '';
  for (const ch of s) out += CHAR_MAP.get(ch) ?? ch;
  return out;
}

/** 完整繁體化：先字元、再詞組 */
export function normalize(s) {
  let t = toTraditional(s);
  for (const [a, b] of PHRASES) if (t.includes(a)) t = t.split(a).join(b);
  return t;
}

/** 整理標點：全形化、去掉句尾句號、壓掉重複空白
 *  英文和數字之間的空白保留 —— 規格要求「英文保留原文」。 */
export function tidyPunct(s, { dropEndPunct = true } = {}) {
  let t = s.trim()
    .replace(/,/g, '，').replace(/\?/g, '？').replace(/!/g, '！')
    .replace(/;/g, '；').replace(/:/g, '：')
    .replace(/。+/g, '。')
    .replace(/\s*，\s*/g, '，')
    .replace(/[ 　]{2,}/g, ' ');
  // 句尾不留標點（句中的逗號、頓號要保留）
  if (dropEndPunct) t = t.replace(/[。，、．,\.\s]+$/g, '');
  return t.trim();
}
